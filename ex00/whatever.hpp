#ifndef WHATEVER_HPP
# define WHATEVER_HPP

/*
** whatever.hpp
**
** 関数テンプレート swap / min / max を定義する。
**
** テンプレートはインスタンス化（実際にどの型で使うかが決まったときに
** コンパイラが具体的なコードを生成すること）が必要なため、
** 「定義そのもの」をヘッダに書く。
** こうしておくと、このヘッダを #include した翻訳単位（.cpp）の中で、
** 使われた型ごとに関数の実体が自動生成される。
**
** （通常の非テンプレート関数の実装をヘッダに書くと、複数の .cpp から
**   include されたときに多重定義エラーになる。だが関数テンプレートは
**   「使われるまで実体が作られない」という特別扱いなので、ヘッダに
**   定義を書くことが許されている＝むしろ必須。）
*/

/*
** swap: a と b の中身を入れ替える。戻り値なし。
** 参照(T&)で受け取るので、呼び出し元の変数そのものが書き換わる。
** 一時変数 tmp に退避してから入れ替える。
*/
template <typename T>
void swap(T& a, T& b)
{
	T tmp = a;
	a = b;
	b = tmp;
}

/*
** min: 小さい方を返す。等しい場合は「2番目(b)」を返す仕様。
** const参照(T const&)で受け取るので、コピーが起きず、かつ
** 引数を書き換えない（読み取り専用）ことを保証する。
** 戻り値も const参照にして、不要なコピーを避ける。
**   - a < b が真 → a が小さい → a を返す
**   - そうでない（a >= b、つまり a > b か a == b）→ b を返す
**     → 等しいときは「そうでない」側に入るので b（2番目）が返る。
*/
template <typename T>
T const& min(T const& a, T const& b)
{
	if (a < b)
		return (a);
	return (b);
}

/*
** max: 大きい方を返す。等しい場合は「2番目(b)」を返す仕様。
**   - a > b が真 → a が大きい → a を返す
**   - そうでない（a <= b、つまり a < b か a == b）→ b を返す
**     → 等しいときは b（2番目）が返る。
*/
template <typename T>
T const& max(T const& a, T const& b)
{
	if (a > b)
		return (a);
	return (b);
}

#endif
